const el = (tag, cls, text) => {
  const n = document.createElement(tag);
  if (cls) n.className = cls;
  if (text != null) n.textContent = text;
  return n;
};

/* ---- specimens ---- */
const panel = document.getElementById("spec-panel");
const specButtons = [...document.querySelectorAll("[data-spec]")];

function showSpec(key) {
  const spec = SPEC[key];
  specButtons.forEach(b => b.setAttribute("aria-pressed", String(b.dataset.spec === key)));
  const wrap = el("div", "eat-spec eat-spec--" + spec.kind);
  wrap.append(el("p", "eat-spec-verdict", spec.verdict));
  spec.rows.forEach(([head, body, note]) => {
    const row = el("div", "eat-spec-row");
    row.append(el("h3", null, head), el("p", null, body));
    if (note && note !== "—") {
      const n = el("p", "eat-note");
      n.append(el("span", "eat-note-k", "What is missing, and why it matters"), document.createTextNode(" " + note));
      row.append(n);
    }
    wrap.append(row);
  });
  panel.replaceChildren(wrap);
}
specButtons.forEach(b => b.addEventListener("click", () => showSpec(b.dataset.spec)));
showSpec("a");

