const fields = document.getElementById("draft-fields");
const formButtons = [...document.querySelectorAll("[data-form]")];
const kept = {};

function showForm(which) {
  formButtons.forEach(b => b.setAttribute("aria-pressed", String(b.dataset.form === which)));
  fields.replaceChildren();
  FORMS[which].forEach(([label, help], i) => {
    const id = which + "-" + i;
    const box = el("div", "space-y-2 break-inside-avoid");
    const lab = el("label", "block text-lg font-semibold", (i + 1) + ". " + label);
    lab.htmlFor = id;
    const hint = el("p", "eat-help", help);
    hint.id = id + "-help";
    const area = el("textarea", "eat-area print:hidden");
    area.id = id;
    area.rows = 4;
    area.maxLength = 8000;
    area.setAttribute("aria-describedby", id + "-help");
    area.value = kept[id] || "";
    const mirror = el("p", "eat-mirror", kept[id] || "");
    area.addEventListener("input", () => {
      kept[id] = area.value;
      mirror.textContent = area.value;
      say("");
    });
    box.append(lab, hint, area, mirror);
    fields.append(box);
  });
}
formButtons.forEach(b => b.addEventListener("click", () => showForm(b.dataset.form)));
showForm("analysis");

